import { randomBytes } from "node:crypto";
import type { EnvEntry } from "../planner/index.js";

/**
 * Build `.env.local` from the env example file of the generated project (CLAUDE.md 4.3, Étape 2
 * task 2). The example is already stripped of its conditional blocks, so it only holds the
 * variables of the selected modules. Every `KEY=value` line is copied with its example value,
 * comments and blank lines are kept, and a variable that looks like a secret with a placeholder
 * value (`change-me…`, empty) gets a random value so the project starts without manual edits.
 * Variables listed by the plan but missing from the example are appended with an empty value.
 * Pure apart from the random generator, which is injectable for tests.
 */

const ENV_LINE = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/;

export type SecretGenerator = () => string;

export const randomSecret: SecretGenerator = () => randomBytes(32).toString("hex");

function isSecretKey(key: string): boolean {
  return /SECRET|PRIVATE_KEY|SIGNING_KEY/.test(key);
}

function isPlaceholder(value: string): boolean {
  const v = value.trim().replace(/^["']|["']$/g, "");
  return v === "" || /^change[-_]?me/i.test(v);
}

export interface EnvLocalResult {
  text: string;
  /** Keys whose value was generated (reported to the user). */
  generated: string[];
}

export function buildEnvLocal(
  exampleText: string,
  planned: readonly EnvEntry[],
  exampleFile: string,
  secret: SecretGenerator = randomSecret,
): EnvLocalResult {
  const generated: string[] = [];
  const seen = new Set<string>();
  const lines = exampleText.split("\n").map((line) => {
    const match = ENV_LINE.exec(line);
    const key = match?.[1];
    const value = match?.[2];
    if (key === undefined || value === undefined) return line;
    seen.add(key);
    if (isSecretKey(key) && isPlaceholder(value)) {
      generated.push(key);
      return `${key}=${secret()}`;
    }
    return line;
  });
  const missing = planned.filter((entry) => !seen.has(entry.key));
  if (missing.length > 0) {
    if (lines.at(-1) === "") lines.pop();
    lines.push("# Declared by the selected modules but absent from the example file", ...missing.map((e) => `${e.key}=${e.value}`), "");
  }
  const header = `# Generated by create-forge-app from ${exampleFile}. Local values only: never commit this file.`;
  return { text: [header, ...lines].join("\n"), generated };
}
